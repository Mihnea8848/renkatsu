"""Converts the game's slider-to-bone formulas into Renkatsu's rule tables.

Input: a locally decompiled copy of the game's ShapeBodyInfoFemale.cs and
ShapeHeadInfoFemale.cs (not part of this repository).
Output: crates/rk-chara/data/shape_{body,head}.rules

Rule file format, one block per driven bone:

    bone <name>
      <comp> = <expr>

<comp> is px/py/pz (local position), rx/ry/rz (local euler degrees, set
together) or sx/sy/sz (local scale). Expressions use + - * / ( ), numbers,
`s.<source>.<comp>` for a slider-driven source channel, `v.<name>` for a
named constant set by the engine, `c.<n>.<comp>` for a
correction value (zero unless the card selects the alternate bone type) and
`wrap(x)` to bring an angle into -180..180.
"""
import re
import sys
from pathlib import Path

COMP = {"vctPos": "p", "vctRot": "r", "vctScl": "s"}


def enum(src: str, name: str):
    m = re.search(r"public enum %s\s*\{(.*?)\}" % name, src, re.S)
    return [x.strip().split("=")[0].strip() for x in m.group(1).split(",") if x.strip()]


def split_args(s: str):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out


def convert(path: Path, out: Path, title: str):
    src = path.read_text(encoding="utf-8")
    dst_names, src_names = enum(src, "Dst(?:Bone)?Name"), enum(src, "Src(?:Bone)?Name")
    start = src.index("public override void Update()")
    end = src.find("private void ", start)
    end2 = src.find("public void ", start)
    stops = [e for e in (end, end2) if e > 0]
    body = src[start:min(stops)] if stops else src[start:]
    vars_ = {}

    def expr(e: str) -> str:
        e = re.sub(r"dictSrc\[(\d+)\]\.(vct\w+)\.([xyz])",
                   lambda m: "s.%s.%s%s" % (src_names[int(m.group(1))], COMP[m.group(2)], m.group(3)), e)
        e = re.sub(r"(?<![\w.])(\d+(?:\.\d+)?(?:E[-+]?\d+)?)f\b", r"\1", e)
        # Head size factor: differs between the male and female skeleton.
        e = e.replace("correctHeadSize", "v.headsize").replace("correctNeckSize", "v.necksize")
        def var(m):
            return "(%s)" % vars_[m.group(0)] if m.group(0) in vars_ else m.group(0)
        e = re.sub(r"(?<![\w.])[A-Za-z_]\w*(?![\w.(])", var, e)
        return e

    lines = [
        "# Copyright (c) 2026 Mihnea Gîrbăcică (Mihnea8848)",
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        "# %s: slider formulas. Generated by tools/gen_shape_rules.py; do not edit." % title,
    ]
    skip_special = False
    for raw in body.splitlines():
        line = raw.strip()
        if "fixCorrectBone" in line:
            # Per-frame nudges that only apply to the alternate bone type.
            break
        m = re.match(r"if \(dictDst\.TryGetValue\((\d+), out value\)\)", line)
        if m:
            lines.append("bone %s" % dst_names[int(m.group(1))])
            skip_special = False
            continue
        if line.startswith("Transform parent = value.trfBone.parent"):
            # Head root: scale that cancels the body's height scaling.
            skip_special = True
            continue
        m = re.match(r"float (\w+) = \(\(typeBone != 0\) \? correctValue\[(\d+)\]\.(vct\w+)\.([xyz]) : 0f\);", line)
        if m:
            vars_[m.group(1)] = "c.%s.%s%s" % (m.group(2), COMP[m.group(3)], m.group(4))
            continue
        m = re.match(r"float (\w+) = \(\(!\(180f < (.+?)\)\) \? .+ : \(.+ - 360f\)\);", line)
        if m:
            vars_[m.group(1)] = "wrap(%s)" % expr(m.group(2))
            continue
        m = re.match(r"value\.trfBone\.SetLocal(Position|Rotation|Scale)([XYZ]?)\((.*)\);", line)
        if m:
            kind, axis, args = m.group(1), m.group(2).lower(), split_args(m.group(3))
            c = {"Position": "p", "Rotation": "r", "Scale": "s"}[kind]
            if skip_special:
                # value.trfBone.SetLocalScale(num3 + (src.sx - 1f), y, z)
                inner = re.search(r"\((dictSrc\[\d+\]\.vct\w+\.[xyz]) - 1f\)", m.group(3))
                lines.append("  headscale = %s" % expr(inner.group(1)))
                skip_special = False
                continue
            if axis:
                lines.append("  %s%s = %s" % (c, axis, expr(args[0])))
            else:
                for a, v in zip("xyz", args):
                    lines.append("  %s%s = %s" % (c, a, expr(v)))
            continue
        if line.startswith("float ") and not skip_special:
            sys.exit("unhandled statement in %s: %s" % (path.name, line))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("%s: %d bones, %d rules" % (out.name, sum(l.startswith("bone") for l in lines), sum("=" in l for l in lines)))


if __name__ == "__main__":
    ref = Path(sys.argv[1])
    data = Path(__file__).resolve().parent.parent / "crates/rk-chara/data"
    convert(ref / "ShapeBodyInfoFemale.cs", data / "shape_body.rules", "body")
    convert(ref / "ShapeHeadInfoFemale.cs", data / "shape_head.rules", "head")
